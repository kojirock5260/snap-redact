/**
 * Service Worker とコンテンツスクリプトの間で交わすメッセージ。
 *
 * 双方が同じ型を見るように 1 箇所へ集めてある。
 * 送る側と受ける側で文字列を書き間違えても、ここを経由していれば型で気づける。
 */
export type Message =
  /** キャプチャ済みの画像を渡して、オーバーレイを開かせる。 */
  | { type: "start"; dataUrl: string }
  /**
   * 開いているオーバーレイを閉じさせる。
   *
   * 連続で起動されたとき、前回のオーバーレイが次のキャプチャに写り込むのを防ぐ。
   */
  | { type: "abort" };
